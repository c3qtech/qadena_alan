import 'package:qadena_alan/proto/qadena/qadena/export.dart';
import 'package:qadena_alan/qadena/common.dart';
import 'package:test/test.dart';

/// The identity hash is a three-way contract between the enclave, the identity
/// provider and this SDK, and these vectors are what hold the Dart side to it.
///
/// The enclave recomputes `CreateCredentialHash` on every claim and every update
/// and rejects a mismatch with a bare ErrGenericPedersen -- no indication that the
/// hash was the problem. So a divergence here surfaces on real devices as "claims
/// just fail", which is why it is pinned rather than assumed.
///
/// Every expected value below was generated by the Go implementation
/// (x/qadena/common.CreateCredentialHash at qadena v1.1.6) and the identical table
/// is asserted on the Go side in the app-server's
/// services/credential_hash_contract_test.go. Neither side may be regenerated to
/// make a failure go away: a mismatch means the chain changed how identities are
/// keyed, and every wallet has to be updated in lockstep.
void main() {
  EncryptablePersonalInfoDetails details({
    required String first,
    required String middle,
    required String last,
    required String birthdate,
    required String gender,
  }) {
    return EncryptablePersonalInfoDetails.create()
      ..firstName = first
      ..middleName = middle
      ..lastName = last
      ..birthdate = birthdate
      ..gender = gender;
  }

  group('createCredentialHash', () {
    test('matches the Go implementation for a plain identity', () {
      expect(
        createCredentialHash(details(
          first: 'jill',
          middle: 'lava',
          last: 'quimba',
          birthdate: '1980-Jan-01',
          gender: 'f',
        )),
        equals('6257c56a61c20e91d518e0648865f8826ed4e2ce1427f0adc11f6bf037650510'),
      );
    });

    test('an empty middle name is a distinct identity, not an error', () {
      expect(
        createCredentialHash(details(
          first: 'jill',
          middle: '',
          last: 'quimba',
          birthdate: '1980-Jan-01',
          gender: 'f',
        )),
        equals('731cbbf6a5ec590ebf35d032e3037c025feebcfe9aea89655700902359f90d9d'),
      );
    });

    // Canonicalization is the whole point: case and surrounding whitespace must
    // not be able to change which identity a credential is keyed under, or the
    // same person could hold two.
    test('case and surrounding whitespace do not change the hash', () {
      const plain = '6257c56a61c20e91d518e0648865f8826ed4e2ce1427f0adc11f6bf037650510';

      expect(
        createCredentialHash(details(
          first: 'JILL',
          middle: 'Lava',
          last: 'Quimba',
          birthdate: '1980-Jan-01',
          gender: 'f',
        )),
        equals(plain),
        reason: 'uppercase must canonicalize to the same identity',
      );

      expect(
        createCredentialHash(details(
          first: '  jill  ',
          middle: ' lava ',
          last: ' quimba ',
          birthdate: '1980-Jan-01',
          gender: 'f',
        )),
        equals(plain),
        reason: 'surrounding whitespace must be trimmed',
      );
    });

    test('a run of internal whitespace collapses to one space', () {
      expect(
        createCredentialHash(details(
          first: 'jill',
          middle: 'de  la',
          last: 'cruz',
          birthdate: '1980-Jan-01',
          gender: 'm',
        )),
        equals('6ce7124ffc5ebefeb418a19057ff902393899c0dfc2abb3b979fa0955fccbb9c'),
      );
    });

    // A tab or a newline is whitespace, not a character to keep. An
    // implementation that only trimmed ' ' would pass every test above and fail
    // this one.
    test('a tab is trimmed and a newline becomes a space', () {
      expect(
        createCredentialHash(details(
          first: 'jill\t',
          middle: 'la\nva',
          last: 'quimba',
          birthdate: '1980-Jan-01',
          gender: 'n',
        )),
        equals('2b07bb773a5b08024a94c9686ed202aa7cfabe95ffe2eba4f92a09460c027081'),
      );
    });

    test('a multi-word surname keeps its single spaces', () {
      expect(
        createCredentialHash(details(
          first: 'maria',
          middle: 'santos',
          last: 'de la cruz',
          birthdate: '1975-Dec-31',
          gender: 'f',
        )),
        equals('a8f6ce0a4dfa9e6703f4a03cad1accbfadee6dfbb8e200380efa930957b94196'),
      );
    });

    test('precomposed accents survive untouched', () {
      expect(
        createCredentialHash(details(
          first: 'josé',
          middle: 'ñuñez',
          last: 'garcía',
          birthdate: '1990-Feb-28',
          gender: 'm',
        )),
        equals('89b88d4de51aef0fd90949fe0f0ed5574b106b656300b69a4f7c9ec64bfc232a'),
      );
    });

    // The trap. Go's unicode.IsSpace covers a no-break space and an ideographic
    // space; anything that only handles ASCII whitespace produces a different
    // hash for a name a user can paste from a document, and the update is
    // rejected with no explanation.
    test('exotic unicode spaces canonicalize like a plain space', () {
      const withPlainSpace = '9ed57a425fe3f800737dcea8f3cae089943c841853515ce0de3478521aba6401';

      for (final space in <String>[' ', ' ', '　', ' ', ' ']) {
        expect(
          createCredentialHash(details(
            first: 'jill',
            middle: 'de${space}la',
            last: 'cruz',
            birthdate: '1980-Jan-01',
            gender: 'f',
          )),
          equals(withPlainSpace),
          reason: 'U+${space.runes.first.toRadixString(16).toUpperCase()} '
              'must be treated as whitespace, as unicode.IsSpace does',
        );
      }
    });
  });

  group('canonicalizeName', () {
    test('collapses, trims and lowercases', () {
      expect(canonicalizeName('  De   LA\tCruz \n'), equals('de la cruz'));
      expect(canonicalizeName(''), equals(''));
      expect(canonicalizeName('   '), equals(''));
      expect(canonicalizeName('quimba'), equals('quimba'));
    });

    test('leaves a canonical name unchanged, so it is idempotent', () {
      for (final name in <String>['jill', 'de la cruz', 'josé', '']) {
        expect(canonicalizeName(canonicalizeName(name)), equals(canonicalizeName(name)));
        expect(canonicalizeName(name), equals(name));
      }
    });
  });
}
